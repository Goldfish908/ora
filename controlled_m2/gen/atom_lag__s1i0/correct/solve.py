    data_path = next(p / "data" / "params.json"
                     for p in (here.parents[1], here.parents[2])
                     if (p / "data" / "params.json").exists())
    d = json.loads(data_path.read_text())
    T = d["periods"]
    m = Model()
    m.hideOutput()
    ship = {t: m.addVar(f"ship_{t}", vtype="I", lb=0)
            for t in range(1, T + 1)}
    inv = {t: m.addVar(f"inv_{t}", vtype="I", lb=0)
           for t in range(1, T + 1)}
    for t in range(1, T + 1):
        prev = d["init_inv"] if t == 1 else inv[t - 1]
        m.addCons(inv[t] == prev + (ship[t - 1] if t > 1 else 0) - d["demand"][t - 1])
    m.setObjective(
        sum(d["ship_cost"][t - 1] * ship[t] for t in range(1, T + 1))
        + sum(d["hold_cost"] * inv[t] for t in range(1, T + 1)))
    m.optimize()
    sol = {
        "objective": round(m.getObjVal(), 6),
        "ship": [round(m.getVal(ship[t]), 6) for t in range(1, T + 1)],
        "inventory": [round(m.getVal(inv[t]), 6) for t in range(1, T + 1)],
    }
    out = Path(__file__).resolve().parent / "solution.json"
    out.write_text(json.dumps(sol, indent=2))
