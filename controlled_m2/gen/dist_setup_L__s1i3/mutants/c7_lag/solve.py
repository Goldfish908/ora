import json
from pathlib import Path

from pyscipopt import Model


def main():
    here = Path(__file__).resolve()
    data_path = next(p / "data" / "params.json"
                     for p in (here.parents[1], here.parents[2])
                     if (p / "data" / "params.json").exists())
    d = json.loads(data_path.read_text())
    W, S, T = d["warehouses"], d["stores"], d["periods"]
    m = Model()
    m.hideOutput()
    ship = {(w, s, t): m.addVar(f"ship_{w}_{s}_{t}", vtype="I", lb=0)
            for w in W for s in S for t in range(1, T + 1)}
    inv = {(s, t): m.addVar(f"inv_{s}_{t}", vtype="I", lb=0)
           for s in S for t in range(1, T + 1)}
    y = {(w, t): m.addVar(f"y_{w}_{t}", vtype="B")
         for w in W for t in range(1, T + 1)}
    for s in S:
        for t in range(1, T + 1):
            prev = d["init_inv"][s] if t == 1 else inv[s, t - 1]
            arr = sum(ship[w, s, t] for w in W)
            m.addCons(inv[s, t] == prev + arr - d["demand"][s][t - 1])
    for w in W:
        for t in range(1, T + 1):
            m.addCons(sum(ship[w, s, t] for s in S) <= d["cap"][w])
            m.addCons(sum(ship[w, s, t] for s in S) <= sum(d["demand"][s][tt] for s in S for tt in range(T)) * y[w, t])
    m.setObjective(
        sum(d["cost"][w][s] * ship[w, s, t]
            for w in W for s in S for t in range(1, T + 1))
        + sum(d["depot_cost"][w] * y[w, t]
              for w in W for t in range(1, T + 1))
        + sum(d["hold_cost"][s] * inv[s, t]
              for s in S for t in range(1, T + 1)))
    m.optimize()
    sol = {
        "objective": round(m.getObjVal(), 6),
        "ship": {f"{w}|{s}": [round(m.getVal(ship[w, s, t]), 6)
                              for t in range(1, T + 1)]
                 for w in W for s in S},
        "inventory": {s: [round(m.getVal(inv[s, t]), 6)
                          for t in range(1, T + 1)] for s in S},
        "depot": {w: [round(m.getVal(y[w, t]), 6)
                      for t in range(1, T + 1)] for w in W},
    }
    out = Path(__file__).resolve().parent / "solution.json"
    out.write_text(json.dumps(sol, indent=2))
    print(f"OBJECTIVE {sol['objective']}")


if __name__ == "__main__":
    main()
