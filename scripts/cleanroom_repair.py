#!/usr/bin/env python3
"""Initialize clean-room Witness assets and run a bounded residual repair DAG."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from ora_agent import llm as llm_mod
from ora_agent.cleanroom import EvidenceMemory, restore_specifications
from ora_agent.cleanroom_witness import initialize_witness, repair_bounded
from scripts.cleanroom_experiment import digest, load_tasks
from ora_agent.oragentbench import read_json, write_json

ROOT = Path(__file__).resolve().parents[1]


def record_specification(source_path: Path | None, record: dict, packet, spec_id: str | None) -> str:
    if source_path is None:
        return ""
    source = read_json(source_path)
    if "candidates" in source:
        return next(candidate["conventions"] for candidate in source["candidates"]
                    if digest(candidate["conventions"]) == record["candidate_sha256"])
    memory = restore_specifications(source)
    asset = memory.generator_specification(packet.scope)
    if asset is None or (spec_id and asset.spec_id != spec_id):
        raise ValueError("no authorized memory specification for this repair")
    if asset.text_sha256 != record["candidate_sha256"]:
        raise ValueError("repair record was not generated by the authorized memory specification")
    return asset.text


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=("witness", "repair"), required=True)
    parser.add_argument("--tasks", required=True)
    parser.add_argument("--run-dir", required=True)
    parser.add_argument("--record")
    parser.add_argument("--spec-source")
    parser.add_argument("--spec-id")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--max-attempts", type=int, choices=(1, 2, 3), default=3)
    parser.add_argument("--llm-timeout", type=float, default=600)
    parser.add_argument("--witness-source")
    parser.add_argument("--api-guard", action="store_true")
    args = parser.parse_args()
    if args.mode == "repair" and not args.record:
        parser.error("--record is required in repair mode")
    llm_mod.REQUEST_TIMEOUT_SEC = args.llm_timeout
    outdir = (ROOT / args.run_dir).resolve()
    if outdir.exists() and any(outdir.iterdir()):
        raise ValueError("repair run directory must be new")
    packets = load_tasks(ROOT / args.tasks)
    dev_packets = [packet for packet in packets if packet.split in {"dev", "audit"}]
    memory = EvidenceMemory()
    oracle_source = (ROOT / args.witness_source).resolve() if args.witness_source else None
    initialization = initialize_witness(memory, dev_packets, outdir / "witness", oracle_source)
    write_json(outdir / "memory.json", memory.public_state())
    if args.mode == "witness":
        print(json.dumps(initialization, ensure_ascii=False, indent=1))
        return

    record_path = (ROOT / args.record).resolve()
    record = read_json(record_path)
    if "record" in record and "task" not in record:
        record = record["record"]
    packet = next(packet for packet in packets if packet.name == record["task"])
    spec_source = (ROOT / args.spec_source).resolve() if args.spec_source else None
    specification = record_specification(spec_source, record, packet, args.spec_id)
    config = llm_mod.load_config()
    result = repair_bounded(memory, packet, record, specification, config,
                            outdir, run_seed=args.seed, max_attempts=args.max_attempts,
                            api_guard=args.api_guard)
    write_json(outdir / "memory_frozen.json", memory.public_state())
    write_json(outdir / "implementation.json", {
        "files": {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
                  for name in ("ora_agent/cleanroom.py", "ora_agent/cleanroom_witness.py",
                               "ora_agent/cleanroom_analysis.py", "ora_agent/oragentbench.py",
                               "ora_agent/api_guard.py", "scripts/cleanroom_repair.py")},
        "tasks_sha256": hashlib.sha256((ROOT / args.tasks).read_bytes()).hexdigest(),
        "source_record_sha256": hashlib.sha256(record_path.read_bytes()).hexdigest(),
        "spec_source_sha256": hashlib.sha256(spec_source.read_bytes()).hexdigest() if spec_source else None,
        "model": config.model, "arguments": vars(args)})
    summary = {key: value for key, value in result.items() if key not in {"record", "dag", "history"}}
    if "record" in result:
        summary["metrics"] = {key: result["record"].get(key) for key in
                              ("feasible", "quality", "true_correct", "objective")}
    print(json.dumps(summary, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
